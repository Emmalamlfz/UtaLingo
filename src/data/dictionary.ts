const entryMap = new Map<string, DictionaryEntry>();
for (const entry of entries) {
  entryMap.set(entry.word, entry);
  if (entry.reading && entry.reading !== entry.word) {
    entryMap.set(entry.reading, entry);
  }
}

export function lookupWord(
  surfaceForm: string,
  basicForm?: string
): DictionaryEntry | null {
  if (basicForm && entryMap.has(basicForm)) return entryMap.get(basicForm)!;
  if (entryMap.has(surfaceForm)) return entryMap.get(surfaceForm)!;
  return null;
}

